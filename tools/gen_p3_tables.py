#!/usr/bin/env python3
"""Generate P3's data tables from the pinned upstream sources (FILE_MAP row 22 + the
NationCreation / TribeNames resources). Owner: P3.

Usage (from the project root): python3 -I engine-rs/tools/gen_p3_tables.py [UPSTREAM] [ENGINE_RS]
  UPSTREAM  defaults to ./upstream (must be at 5b75bd3)
  ENGINE_RS defaults to the directory above this script

Writes:
  crates/of-engine/src/map/maps_gen.rs              (whole file, from engine-api/src/game/Maps.gen.ts)
  crates/of-engine/src/setup/tribe_names.rs         (block between @generated markers, resources/tribeNameThemes.json)
  crates/of-engine/src/setup/nation_creation.rs     (block between @generated markers, engine/src/game/NationCreation.ts)
`--check` exits 1 if any output would change (CI drift guard).
"""
import json, os, re, sys

ARGS = [a for a in sys.argv[1:] if not a.startswith('--')]
CHECK = '--check' in sys.argv
HERE = os.path.dirname(os.path.abspath(__file__))
UP = os.path.abspath(ARGS[0]) if len(ARGS) > 0 else os.path.abspath('upstream')
RS = os.path.abspath(ARGS[1]) if len(ARGS) > 1 else os.path.dirname(HERE)
ENG = os.path.join(RS, 'crates/of-engine/src')


def rs_str(s):
    return json.dumps(s, ensure_ascii=False)  # JSON escapes are valid Rust string escapes for these inputs


# ---------------------------------------------------------------- a tiny JS literal parser
class P:
    def __init__(self, s):
        self.s, self.i = s, 0

    def ws(self):
        s = self.s
        while self.i < len(s):
            if s[self.i].isspace():
                self.i += 1
            elif s.startswith('//', self.i):
                self.i = s.index('\n', self.i)
            elif s.startswith('/*', self.i):
                self.i = s.index('*/', self.i) + 2
            else:
                break

    def peek(self):
        self.ws()
        return self.s[self.i]

    def eat(self, c):
        self.ws()
        assert self.s.startswith(c, self.i), (c, self.s[self.i:self.i + 40])
        self.i += len(c)

    def ident(self):
        self.ws()
        m = re.compile(r'[A-Za-z_$][A-Za-z0-9_$.]*').match(self.s, self.i)
        assert m, self.s[self.i:self.i + 40]
        self.i = m.end()
        return m.group(0)

    def value(self):
        c = self.peek()
        if c == '"':
            j = self.i + 1
            while self.s[j] != '"':
                j += 2 if self.s[j] == '\\' else 1
            v = json.loads(self.s[self.i:j + 1])
            self.i = j + 1
            return v
        if c == '[':
            self.eat('[')
            out = []
            while self.peek() != ']':
                out.append(self.value())
                if self.peek() == ',':
                    self.eat(',')
            self.eat(']')
            return out
        if c == '{':
            self.eat('{')
            out = {}
            while self.peek() != '}':
                k = self.ident() if self.peek() != '"' else self.value()
                self.eat(':')
                out[k] = self.value()
                if self.peek() == ',':
                    self.eat(',')
            self.eat('}')
            return out
        m = re.compile(r'-?[0-9]+(\.[0-9]+)?').match(self.s, self.i)
        if m:
            self.i = m.end()
            return float(m.group(0)) if m.group(1) else int(m.group(0))
        w = self.ident()
        if w in ('true', 'false'):
            return w == 'true'
        return ('ident', w)


# ---------------------------------------------------------------- Maps.gen.ts
def gen_maps():
    src = open(os.path.join(UP, 'packages/engine-api/src/game/Maps.gen.ts'), encoding='utf-8').read()
    enum_body = src[src.index('export enum GameMapType {') + len('export enum GameMapType {'):]
    enum_body = enum_body[:enum_body.index('\n}')]
    enum = re.findall(r'^\s*([A-Za-z0-9_]+) = ("[^"]*"),', enum_body, re.M)
    enum = [(k, json.loads(v)) for k, v in enum]
    emap = dict(enum)
    a = src.index('export const maps: readonly MapInfo[] = ')
    p = P(src)
    p.i = a + len('export const maps: readonly MapInfo[] = ')
    maps = p.value()
    out = []
    w = out.append
    w('//! `engine-api/src/game/Maps.gen.ts` (2,310 generated lines). Owner: **P3**, status')
    w('//! **generated** (FILE_MAP row 22).')
    w('//!')
    w('//! @generated by `tools/gen_p3_tables.py` from `upstream/packages/engine-api/src/game/Maps.gen.ts`')
    w('//! (itself generated from `map-generator/assets/maps/*/info.json`). DO NOT EDIT; re-run the')
    w('//! script on an upstream bump (`--check` detects drift).')
    w('//!')
    w('//! Only the sim-relevant `MapInfo` fields are kept: the map-picker metadata (categories,')
    w('//! featured rank, author, location, translation keys, layers) is view-only.')
    w('')
    w('/// `CustomTribe` (`Maps.gen.ts:235-238`).')
    w('#[derive(Clone, Copy, Debug, PartialEq, Eq)]')
    w('pub struct CustomTribeInfo {')
    w('    pub name: &\'static str,')
    w('    pub coordinates: Option<[u32; 2]>,')
    w('}')
    w('')
    w('/// `MapInfo` (`Maps.gen.ts:200-233`), sim-relevant fields.')
    w('#[derive(Clone, Copy, Debug, PartialEq, Eq)]')
    w('pub struct MapInfo {')
    w('    /// `id: GameMapName` (the enum key).')
    w('    pub id: &\'static str,')
    w('    /// `type: GameMapType` (the wire name, `GameConfig.gameMap`).')
    w('    pub map_type: &\'static str,')
    w('    pub default_nation_count: u32,')
    w('    pub special_team_count: Option<u32>,')
    w('    pub hidden: bool,')
    w('    pub themes: Option<&\'static [&\'static str]>,')
    w('    pub custom_tribes: Option<&\'static [CustomTribeInfo]>,')
    w('}')
    w('')
    w('/// `enum GameMapType` (`Maps.gen.ts:5-142`): `(key, value)` in declaration order.')
    w('#[rustfmt::skip]')
    w('pub static GAME_MAP_TYPES: &[(&str, &str)] = &[')
    for k, v in enum:
        w(f'    ({rs_str(k)}, {rs_str(v)}),')
    w('];')
    w('')
    w('/// `maps` (`Maps.gen.ts:251-…`), in source order.')
    w('#[rustfmt::skip]')
    w('pub static MAPS: &[MapInfo] = &[')
    for m in maps:
        t = m['type']
        assert t[0] == 'ident' and t[1].startswith('GameMapType.'), t
        mt = emap[t[1][len('GameMapType.'):]]
        assert m['id'] == t[1][len('GameMapType.'):], (m['id'], t)
        th = m.get('themes')
        ct = m.get('customTribes')
        w('    MapInfo {')
        w(f'        id: {rs_str(m["id"])},')
        w(f'        map_type: {rs_str(mt)},')
        w(f'        default_nation_count: {m["defaultNationCount"]},')
        w(f'        special_team_count: {"Some(%d)" % m["specialTeamCount"] if "specialTeamCount" in m else "None"},')
        w(f'        hidden: {"true" if m.get("hidden") else "false"},')
        w('        themes: ' + ('None,' if th is None else 'Some(&[' + ', '.join(rs_str(x) for x in th) + ']),'))
        if ct is None:
            w('        custom_tribes: None,')
        else:
            w('        custom_tribes: Some(&[')
            for c in ct:
                assert set(c) <= {'name', 'coordinates'}, c
                co = c.get('coordinates')
                cs = 'None' if co is None else 'Some([%d, %d])' % (co[0], co[1])
                w(f'            CustomTribeInfo {{ name: {rs_str(c["name"])}, coordinates: {cs} }},')
            w('        ]),')
        w('    },')
    w('];')
    w('')
    w('/// `maps.find((m) => m.type === mapType)` (`TribeNames.ts:22-25`).')
    w('pub fn map_info(map_type: &str) -> Option<&\'static MapInfo> {')
    w('    MAPS.iter().find(|m| m.map_type == map_type)')
    w('}')
    w('')
    w('/// `Object.values(GameMapType).includes(name)`: is `name` a known map wire name?')
    w('pub fn is_game_map_type(name: &str) -> bool {')
    w('    GAME_MAP_TYPES.iter().any(|(_, v)| *v == name)')
    w('}')
    return '\n'.join(out) + '\n', len(enum), len(maps)


# ---------------------------------------------------------------- tribeNameThemes.json
def gen_themes():
    d = json.load(open(os.path.join(UP, 'resources/tribeNameThemes.json'), encoding='utf-8'))
    out = ['/// `resources/tribeNameThemes.json`: `(theme, prefixes, suffixes)` in file order.',
           '#[rustfmt::skip]', 'static TRIBE_NAME_THEMES: &[(&str, &[&str], &[&str])] = &[']
    for k, v in d.items():
        assert set(v) == {'prefixes', 'suffixes'}, k
        out.append(f'    ({rs_str(k)}, &[' + ', '.join(rs_str(x) for x in v['prefixes']) + '], &[' +
                   ', '.join(rs_str(x) for x in v['suffixes']) + ']),')
    out.append('];')
    return '\n'.join(out) + '\n', len(d)


# ---------------------------------------------------------------- NationCreation.ts
def block(src, start, end='\n];'):
    a = src.index(start) + len(start)
    return src[a:src.index(end, a)]


def gen_nation_tables():
    src = open(os.path.join(UP, 'packages/engine/src/game/NationCreation.ts'), encoding='utf-8').read()
    tpl_src = block(src, 'const NAME_TEMPLATES: NameTemplate[] = [')
    p = P('[' + tpl_src + ']')
    templates = p.value()
    nouns = P('[' + block(src, 'const NOUNS = [') + ']').value()
    o_to_oes = P(block(src, 'const O_TO_OES = new Set(', ');')).value()
    special = P(block(src, 'const SPECIAL_PLURALS = new Map(', ');')).value()
    out = ['/// `NAME_TEMPLATES` (`NationCreation.ts:177-…`).', '#[rustfmt::skip]', 'static NAME_TEMPLATES: &[&[Part]] = &[']
    for t in templates:
        parts = []
        for x in t:
            if isinstance(x, str):
                parts.append(f'Part::Lit({rs_str(x)})')
            elif x == ('ident', 'NOUN'):
                parts.append('Part::Noun')
            elif x == ('ident', 'PLURAL_NOUN'):
                parts.append('Part::Plural')
            else:
                raise SystemExit(f'bad template part {x}')
        out.append('    &[' + ', '.join(parts) + '],')
    out.append('];')
    out.append('/// `NOUNS` (duplicates kept: they weight the draw).')
    out.append('#[rustfmt::skip]')
    out.append('static NOUNS: &[&str] = &[' + ', '.join(rs_str(x) for x in nouns) + '];')
    out.append('/// `O_TO_OES` (`new Set([...])`).')
    out.append('#[rustfmt::skip]')
    out.append('static O_TO_OES: &[&str] = &[' + ', '.join(rs_str(x) for x in o_to_oes) + '];')
    out.append('/// `SPECIAL_PLURALS` (`new Map([...])`).')
    out.append('#[rustfmt::skip]')
    out.append('static SPECIAL_PLURALS: &[(&str, &str)] = &[' + ', '.join(f'({rs_str(a)}, {rs_str(b)})' for a, b in special) + '];')
    return '\n'.join(out) + '\n', len(templates), len(nouns)


def splice(path, name, body):
    s = open(path, encoding='utf-8').read()
    b = f'// @generated-begin {name} (tools/gen_p3_tables.py; DO NOT EDIT)\n'
    e = f'// @generated-end {name}\n'
    assert b in s and e in s, (path, name)
    return s[:s.index(b) + len(b)] + body + s[s.index(e):]


def emit(path, text):
    old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
    if old == text:
        return False
    if CHECK:
        print(f'DRIFT {path}')
        return True
    open(path, 'w', encoding='utf-8').write(text)
    print(f'wrote {path}')
    return True


maps_rs, n_enum, n_maps = gen_maps()
themes_rs, n_themes = gen_themes()
nat_rs, n_tpl, n_nouns = gen_nation_tables()
drift = False
drift |= emit(os.path.join(ENG, 'map/maps_gen.rs'), maps_rs)
p = os.path.join(ENG, 'setup/tribe_names.rs')
drift |= emit(p, splice(p, 'tribe_name_themes', themes_rs))
p = os.path.join(ENG, 'setup/nation_creation.rs')
drift |= emit(p, splice(p, 'nation_name_tables', nat_rs))
print(f'GameMapType {n_enum}, maps {n_maps}, themes {n_themes}, templates {n_tpl}, nouns {n_nouns}')
sys.exit(1 if (CHECK and drift) else 0)
